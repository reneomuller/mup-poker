const B = process.env.BASE || 'http://localhost:3077/api/game';
const post = async (body) => (await fetch(B, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })).json();
const get = async (h = {}, q = '') => (await fetch(B + q, { headers: h })).json();
const D = (op, x = {}) => post({ op, ...x });
const assert = (c, m) => { if (!c) { console.error('FAIL:', m); process.exitCode = 1; } else console.log('ok  ', m); };
await D('reset', { confirm: 'RESET', keepPlayers: false });
let st = await get(); const T = st.teams.map((t) => t.id);
const a = await post({ op: 'register', name: 'Alice', team: T[0], pin: '1111' });
const b = await post({ op: 'register', name: 'Bob', team: T[1], pin: '2222' });
assert((await get({}, '?view=dealer')).dealer, 'dealer open without password');
await D('phase', { phase: 'betting' });
let r = await post({ op: 'submit', sid: a.sid, pin: '1111', in: { [T[1]]: { amt: 1000000, why: 'Bob team rocks' } }, notes: { [T[1]]: { like: 'Silný tým', doubt: 'Nevěřím cenám' } } });
assert(r.ok, 'submit with two-part notes');
r = await post({ op: 'submit', sid: b.sid, pin: '2222', in: { [T[0]]: { amt: 1000000, why: 'Alice' } } });
const dv = await get({}, '?view=dealer');
const an = dv.dealer.rows.find((x) => x.name === 'Alice').slip.notes[T[1]];
assert(an.like === 'Silný tým' && an.doubt === 'Nevěřím cenám', 'notes stored as like/doubt');
r = await D('pin', { team: T[1], q: 'Čemu nevěříš?', a: 'Nevěřím cenám' });
assert(r.ok, 'pin ok');
st = await get();
assert(st.pins.length === 1 && st.pins[0].a === 'Nevěřím cenám' && !JSON.stringify(st.pins).includes('Alice'), 'pin public, no name');
await D('unpin', { id: st.pins[0].id });
assert((await get()).pins.length === 0, 'unpin ok');
await D('phase', { phase: 'closed' }); await D('showdown');
await D('rjSave', { in: Object.fromEntries(T.map((t, i) => [t, { amt: [5e6, 5e6, 0, 0, 0, 0][i], why: 'Důvod pro ' + t }]).filter(([, e]) => e.amt)) });
r = await D('rjReveal'); assert(r.ok, 'rj reveal');
r = await D('revalue', { V: { [T[1]]: 20000000 }, why: { [T[1]]: 'Pivot na B2B', [T[0]]: 'Jen zpráva bez přecenění' } });
assert(r.ok, 'revalue with private messages');
const ma = await get({ 'x-sid': a.sid, 'x-pin': '1111' }), mb = await get({ 'x-sid': b.sid, 'x-pin': '2222' });
assert(ma.me.msgs.some((m) => m.text === 'Jen zpráva bez přecenění') && !JSON.stringify(ma.me.msgs).includes('Pivot na B2B'), 'team A sees only its messages');
assert(mb.me.msgs.some((m) => m.kind === 'revalue' && m.text === 'Pivot na B2B') && mb.me.msgs.some((m) => m.kind === 'smart'), 'team B sees revalue + smart money reason');
assert(!JSON.stringify(await get()).includes('Pivot na B2B'), 'messages not in public state');
assert(ma.me.series.length >= 1 && typeof ma.me.invested === 'boolean', 'portfolio series present');

// start valuation: only before anyone has invested
let rr = await D('startValuation', { V: 500000 });
assert(rr.ok === false, 'start valuation locked after investing');
await D('reset', { confirm: 'RESET', keepPlayers: true });
rr = await D('startValuation', { V: 500000 });
let s3 = await get();
assert(rr.ok && s3.startV === 500000 && s3.teams.every((t) => t.V === 500000), 'start valuation set to 500k before investing');
await D('reset', { confirm: 'RESET', keepPlayers: true });
assert((await get()).startV === 500000, 'reset keeps chosen start valuation');
// reasons can be added after submitting
await D('phase', { phase: 'betting' });
const T2 = (await get()).teams.map((t) => t.id);
rr = await post({ op: 'submit', sid: a.sid, pin: '1111', in: { [T2[1]]: { amt: 1000000, why: '' } } });
assert(rr.ok, 'submit without reasons');
await D('phase', { phase: 'closed' });
rr = await post({ op: 'reasons', sid: a.sid, pin: '1111', in: { [T2[1]]: 'Doplněno po uzavření' } });
const dv2 = await get({}, '?view=dealer');
assert(rr.ok && dv2.dealer.rows.find((x) => x.name === 'Alice').slip.in[T2[1]].why === 'Doplněno po uzavření', 'reason added after close, amount unchanged');
